"""Run the adversarial catalogue and print/write the results.

    .venv/bin/python code/evaluation/adversarial_review.py            # table
    .venv/bin/python code/evaluation/adversarial_review.py --write    # also write adversarial_review.md
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from adversarial_attacks import run_all  # noqa: E402


def markdown(results: list[dict]) -> str:
    import json
    counts = Counter(r["verdict"] for r in results)
    audit = HERE.parents[1] / "runs" / "audit.jsonl"
    left_out = Counter()
    if audit.is_file():
        for line in audit.read_text(encoding="utf-8").splitlines():
            row = json.loads(line)
            for _, why in row.get("dropped", []):
                left_out[why] += 1
            left_out["a retained or preserved record with no allowed operation"] += len(row.get("unplanned", []))
    L = ["# Adversarial review", "",
         "Generated by `code/evaluation/adversarial_review.py --write`. Every attack builds a tiny fictional dataset (example.test addresses, 555 numbers) and runs the "
         "real loader, indexer, pipeline and row verifier; the output-rule attacks call the row verifier directly. Regression tests: `code/tests/test_adversarial.py`.", "",
         "Verdicts. **blocked**: the expected answer was produced. **detected**: the answer was not produced but the system refused (loader, indexer or row verifier) or "
         "named the problem in the run output without stopping. **exploitable**: a wrong answer was emitted silently. Severity HIGH means a false COMPLETE.", "",
         f"Result: {counts['blocked']} blocked, {counts['detected']} detected, {counts['exploitable']} exploitable, of {len(results)} attacks.", "",
         "Order of work: the first run (before any change) found 19 exploitable results. Four of them were mistakes in my own fixtures (a shared phone number, missing "
         "system hints, an OCR example one edit from only one address, an expectation mislabelled), corrected and re-run. The rest were real and are listed under fixes.", "",
         "| Id | Area | Attack | Expected | Actual | Verdict | Severity |", "|---|---|---|---|---|---|---|"]
    for r in results:
        cell = lambda s: s.replace("|", "/").replace("\n", " ")[:210]
        L.append(f"| {r['id']} | {r['area']} | {cell(r['attack'])} | {cell(r['expected'])} | {cell(r['actual'])} | {r['verdict']} | {r['severity'] or '-'} |")
    L += ["", "## Defects reproduced and fixed", "",
          "| Defect | Reproduction | Impact | Fix | Real output changed? |", "|---|---|---|---|---|",
          "| A stray `result=NOT_FOUND` or `rows=0` inside a live JSON or SQL account record made the account ABSENT | E3, E3b | false COMPLETE | `state.py`: a structured account record with a non-null `account_status` is PRESENT | no (0 such records in the dataset) |",
          "| On an exact timestamp tie the higher file number won, so two exports in a different order flipped COMPLETE and INCOMPLETE | E6b, E6c | false COMPLETE | `ledger.py`: on a tie the unsafe reading (data still there) wins | no (0 ties in the dataset) |",
          "| An analytics row without an `email` key was never interpreted and silently dropped | I3b | false COMPLETE | `state.py`: structured analytics rows are read by their columns | no (0 unreadable structured rows) |",
          "| A tombstone lookup that returned nothing was read as a redacted tombstone | P7c | false COMPLETE | `state.py`: absent lookup is ABSENT, which the run now flags | no |",
          "| The row verifier accepted duplicate steps, findings without remediation or closing verification, and citations of unrelated files | O1, O3, O3b, O4 | invalid or unproven rows | `verify.py`: duplicate check, finding follow-up check, and cited file must name the resource or cover the system | no (518 rows pass) |",
          "| A resource linked to a case but unreadable or without an allowed operation vanished silently | E7, P4b, P6b, P7c | false COMPLETE | `ledger.py` and `main.py`: recorded as `dropped` or `unplanned` and counted in the run output (detection only) | no |",
          "| Evidence path `../x` in the manifest was followed | `test_security.py` | read outside the dataset | `data.py`: lexical containment check | no |",
          "| An interrupted run could leave a half-written output.csv | `test_security.py` | partial output | `main.py`: write to `.partial`, then rename | no |", "",
          "## Open defects", "",
          "1. **HIGH, flagged but not prevented: linked resources with no readable state or no allowed operation.** E7, P4b, P6b. "
          "The contract has no operation for a retained record that is gone or a backup of unknown restore state, so a correct INCOMPLETE row cannot be written. "
          "The run prints the count and `runs/audit.jsonl` lists them (`dropped`, `unplanned`). In the real run: "
          + (", ".join(f"{n} x {why}" for why, n in sorted(left_out.items()) if n) or "see runs/audit.jsonl") + ". Smallest fix needs a decision on what to emit; not changed.",
          "2. **HIGH, documented: three cases with no identifiable resource are answered COMPLETE with no steps** (case_45 reported COMPLETE, case_61 PARTIALLY_COMPLETE, case_63 NOT_STARTED). "
          "For case_61 and case_63 the workflow's own claim says work remains, so COMPLETE is probably wrong. There is no evidence-based INCOMPLETE row to write (it needs a finding), so they are flagged, not changed.",
          "3. **MEDIUM: P3b.** An analytics row whose identifier columns are null but whose free-text note holds the email is treated as anonymized. Whether that is still attributable is a specification question.",
          "4. **LOW: no size limits on evidence files**, and a symlink inside the dataset folder is followed (the dataset is trusted participant input).",
          "5. **Not end to end: I4.** Ambiguous workflow rows are tested at the matcher level (`_forced_assignments`), not through a full synthetic pipeline.", "",
          "## Tested and untested", "",
          "Tested on constructed data: the identity, evidence, policy, state-flow and output attacks in the table. Tested on the real dataset: the 518 rows pass the verifier with the new checks and the output is byte-identical after the fixes.",
          "**Not tested:** OCR or PDF ambiguity end to end (only the repair function), replica drift between SQL snapshots, real provider failures (rate limits, timeouts), very large or hostile files, "
          "non-English identifiers in evidence, concurrent runs, and any hidden-set behaviour. A passing synthetic attack shows a rule works, not how often the situation occurs.", ""]
    return "\n".join(L)


def main() -> int:
    results = run_all()
    for r in results:
        flag = {"blocked": "ok  ", "detected": "DET ", "exploitable": "EXPL"}[r["verdict"]]
        print(f"{flag} {r['id']:4s} {r['area']:11s} {r['attack'][:78]}")
        if r["verdict"] != "blocked":
            print(f"       expected: {r['expected'][:100]}\n       actual:   {r['actual'][:200]}")
    print(Counter(r["verdict"] for r in results))
    if "--write" in sys.argv:
        (HERE / "adversarial_results.json").write_text(__import__("json").dumps(results, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        (HERE / "adversarial_review.md").write_text(markdown(results), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
